"""未定事件簿（tears-of-themis）专属规则常量。

与 genshin/、starrail/、zenless/ 并列的第四条线，共用同一套 common/
（yaml_io / keys / colors / body_cache）。解析逻辑见 parse.py，规则出处见 RULES.md。

未定的信息结构与另三端不同，三点差异都在这里：

1. **活动在资讯栏（`type=3`），版本公告在公告栏（`type=1`）** —— 两个栏目都要抓。
   另三端的活动公告都在公告栏，所以 common.extractor 的 `NEWS_TYPE_MAP` 只给未定
   登记了资讯栏；公告栏那一路要显式传 `news_type`。
2. **一个活动拆成好几篇发**，所以没有「总纲」这种东西可用，也没有归并机制
   （裁定：一篇帖子一条，日期只认本篇自己的时段，见 RULES §2.3）。
3. **卡池会返场**，标题逐字相同 ⇒ 卡池身份必须带开始日期（RULES §4.2），
   这一条写在 common/keys.py 里（`DATED_BANNER_GAMES`）。

所有规则都用真实公告核对过，核对样本见 fixtures/（由 selftest.py 断言）。
"""
import re

# ─── 抓取参数 ────────────────────────────────────────────

GAME = "tears-of-themis"

# 两个栏目：活动在资讯栏，版本停服更新公告在公告栏（RULES §1.1）
NEWS_TAB = 3
VERSION_TAB = 1

# `getNewsList` 的 page_size 上限就是 50（传 100 会静默回落成 20），而它**不能翻页**
# （`last_id` 返 0 条，`offset`/`page` 被忽略）。所以 50 条 ≈ 5 周是硬上限，
# 比一个版本周期（37~70 天）还短 —— 这是「首次回填=不补」与「pending 尽量不用」的根因。
PAGE_SIZE = 50

# ─── 公告栏：版本更新 ────────────────────────────────────

# 停服更新公告的标题形如「5.6版本更新丨2月10日08:00停服更新公告」——版本号与开服日
# 都现成，**不用取正文**（RULES §2.4-1）。正文只做交叉校验，不解析。
VERSION_NOTES_PATTERN = r"(\d+)\.(\d+)版本更新丨(\d{1,2})月(\d{1,2})日\s*\d{1,2}:\d{2}\s*停服更新公告"
# 未定的停服公告**不给版本名**（原神/绝区零写「版本『X』」，未定只写「全新6.0版本即将上线」），
# 所以标题只能是版本号形式，无法沿用三端的「版本「名」停服更新」。
VERSION_UPDATE_TITLE = "《未定事件簿》{ver} 版本停服更新"

# ─── 第一道闸：标题负向名单（非游戏内内容，不取正文即丢）───
#
# 只用标题就能判掉 19/50 篇，省掉 19 次正文请求（RULES §2.2）。判据是「非游戏内内容」：
# 实体周边、站外促销、运维帖、宣传帖。名单是**必要的恶**——这些帖的标题没有共同的
# 结构特征，只能逐类列举；每一条都注明为什么非列不可。
TITLE_SKIP_KEYWORDS = (
    "日常更新公告",   # 每周运维帖（38/45 的公告栏帖都是它）
    "未成年人",       # 政策通知
    "问题处理说明",   # 修 bug
    "插画分享", "OST", "捐赠证书", "PV丨",   # 宣传 / 公示帖
    "未定事件簿×", "《未定事件簿》×",        # 站外联名（茉酸奶、TOPTOY…）
    "周边", "手办", "盲盒", "预售",          # 实体周边
    "会员积分",       # 米游社商城活动，不在游戏内
    "商城上新",       # 纯商城折扣，无活动玩法
    "系统更新",       # 常驻系统更新（「逸梦」梦笺）
    "主线更新",       # 版本内容，不是限时活动
    # 累充是名单里**唯一「带完整时段仍要排除」**的：光靠第二道闸拦不住它，
    # 必须在这里挡（RULES §2.2）。
    "限时累充",
)

# ⚠️ 名单里**故意没有** `快乐丨`：`中秋快乐丨…` / `教师节快乐丨…` 带游戏内登录奖励，
# 是登录福利，不是宣传帖（裁定，见 RULES §2.2 的注）。

# ─── 第三关：复刻二分 ────────────────────────────────────

# `往期复刻丨…` 下混着两种东西，必须再分（RULES §2.2 第三关）
REPRINT_TOPIC = "往期复刻"
# 卡池信号。判据取**整条标题或正文**，不只是子标题：
#   - 轮替返场的信号在主题里（`轮替女神之影更新丨夏彦SSR【夏花永隽】限时返场`）
#   - 生日系列复刻的信号只在正文里（`往期复刻丨莫弈生日系列限时复刻` 正文通篇女神之影）
# 实测资讯栏 50 篇：标题含 `女神之影` 的 4 篇全是卡池；另 4 篇复刻帖正文 0 次命中 ——
# 判据干净（`女神之泪` 是道具，不是它，别放宽成 `女神之`）。
BANNER_KEYWORD = "女神之影"
# 礼包复刻 / 商城上架 → 不上日历。`上架` 是 2026-09-25 新出现的一篇补进来的：
# `往期复刻丨往期绮思限定甜心服饰常驻上架短笺兑换所`（9/30~10/17）正文通篇是礼包上架
# 与兑换所，没有玩法；它主题是往期复刻、所以躲过了 `商城上新` 那道标题名单。
REPRINT_DROP_KEYWORDS = ("活动系列", "礼包", "上架")

# ─── 第四关：版本大活动的官方复合标签 ──────────────────────
#
# 判据是官方自己贴的 `〔修饰语〕活动「活动名」`，修饰语 = 大型〈季节〉 / 〈◯◯〉主题 /
# 〈◯◯〉联动。332 天全库（B站 500 条动态）只命中 4 个活动、零假阳性，一句一期
# （RULES §2.4-4）。**修饰语本身就是分类器**：
#   大型新春活动「故城长燃的薪火」(5.6) / 萌兽学院主题活动「萌兽在校生」(5.8)
#   阿加莎联动活动「何人生还」(5.9) / 海岛主题活动「NXX-非常假日」(6.1)   ← 都是 17 天
# 被它正确排除的：限时活动「心跳低喃时」、莫弈生日活动「岁悦同欢·莫弈篇」。
# ⚠️ 标签只在**正文**里，标题（subject）没有 —— 好在第二道闸本来就要取正文。
BIG_EVENT_LABEL = re.compile(
    r"(?:大型[一-龥]{0,6}|[一-龥]{2,6}主题|[一-龥]{2,8}联动)活动「([^」]{2,20})」")

# ─── 归类（其余类型）─────────────────────────────────────

